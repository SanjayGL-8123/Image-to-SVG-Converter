/**
 * Pure JavaScript Image Vectorizer Engine
 * Supports Vector Path Tracing, Palette Quantization, RDP Simplification,
 * Bezier Curve Fitting, Monochrome Line Art, and Embedded Data-URI Fallbacks.
 */

class VectorizerEngine {
  constructor() {
    this.canvas = document.createElement('canvas');
    this.ctx = this.canvas.getContext('2d', { willReadFrequently: true });
  }

  /**
   * Main Entry Point to Vectorize an HTML Image Element
   */
  async vectorize(imgElement, options = {}) {
    const startTime = performance.now();

    const mode = options.mode || 'vector'; // 'vector', 'monochrome', 'embedded'
    const colorCount = parseInt(options.colors || 16, 10);
    const epsilon = parseFloat(options.epsilon || 1.2);
    const minArea = parseInt(options.minArea || 10, 10);
    const blurRadius = parseInt(options.blur || 0, 10);
    const transparentBg = !!options.transparentBg;
    const curveType = options.curveType || 'bezier'; // 'bezier' or 'polygon'

    const width = imgElement.naturalWidth || imgElement.width || 300;
    const height = imgElement.naturalHeight || imgElement.height || 300;

    // Handle Embedded Mode directly
    if (mode === 'embedded') {
      const embeddedSvg = this.generateEmbeddedSvg(imgElement, width, height);
      const durationMs = Math.round(performance.now() - startTime);
      return {
        svgString: embeddedSvg,
        palette: [],
        pathCount: 1,
        pointCount: 4,
        durationMs
      };
    }

    // Set canvas dimensions
    this.canvas.width = width;
    this.canvas.height = height;
    this.ctx.clearRect(0, 0, width, height);

    // Apply optional pre-blur filtering
    if (blurRadius > 0) {
      this.ctx.filter = `blur(${blurRadius}px)`;
    } else {
      this.ctx.filter = 'none';
    }

    this.ctx.drawImage(imgElement, 0, 0, width, height);
    const imageData = this.ctx.getImageData(0, 0, width, height);

    let svgPaths = [];
    let palette = [];

    if (mode === 'monochrome') {
      const result = this.processMonochrome(imageData, width, height, epsilon, minArea, curveType);
      svgPaths = result.paths;
      palette = result.palette;
    } else {
      // Multi-color Vector Mode
      const result = this.processColorVector(imageData, width, height, colorCount, epsilon, minArea, transparentBg, curveType);
      svgPaths = result.paths;
      palette = result.palette;
    }

    // Assemble SVG markup
    let totalPoints = 0;
    let pathTags = [];

    for (const p of svgPaths) {
      totalPoints += p.pointCount;
      const strokeAttr = p.stroke ? `stroke="${p.stroke}" stroke-width="${p.strokeWidth || 0.5}"` : '';
      pathTags.push(`  <path d="${p.d}" fill="${p.fill}" ${strokeAttr} stroke-linejoin="round" stroke-linecap="round"/>`);
    }

    const svgHeader = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">`,
      '  <!-- Generated by SPVM VectorCraft Engine -->',
      '  <style>path { vector-effect: non-scaling-stroke; }</style>',
      ...pathTags,
      '</svg>'
    ].join('\n');

    const durationMs = Math.round(performance.now() - startTime);

    return {
      svgString: svgHeader,
      palette,
      pathCount: svgPaths.length,
      pointCount: totalPoints,
      durationMs
    };
  }

  /**
   * Embedded SVG Generator
   */
  generateEmbeddedSvg(imgElement, w, h) {
    const tempCanvas = document.createElement('canvas');
    tempCanvas.width = w;
    tempCanvas.height = h;
    const tCtx = tempCanvas.getContext('2d');
    tCtx.drawImage(imgElement, 0, 0, w, h);
    const dataUrl = tempCanvas.toDataURL('image/png');

    return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <title>Vectorized Embedded Asset</title>
  <image width="${w}" height="${h}" preserveAspectRatio="xMidYMid meet" href="${dataUrl}"/>
</svg>`;
  }

  /**
   * Color Vectorization Logic: Palette Quantization + Contour Extraction
   */
  processColorVector(imageData, w, h, colorCount, epsilon, minArea, transparentBg, curveType) {
    const data = imageData.data;
    const pixelCount = w * h;

    // Step 1: Extract RGB sample pixels
    const sampleStep = Math.max(1, Math.floor(pixelCount / 4000));
    const samples = [];
    for (let i = 0; i < data.length; i += 4 * sampleStep) {
      if (data[i + 3] > 30) { // skip fully transparent pixels
        samples.push([data[i], data[i + 1], data[i + 2]]);
      }
    }

    // Step 2: Quantize palette using K-Means clustering
    const paletteRgb = this.kMeansQuantize(samples.length > 0 ? samples : [[0,0,0]], Math.min(colorCount, samples.length || 1));
    const paletteHex = paletteRgb.map(c => this.rgbToHex(c[0], c[1], c[2]));

    // Step 3: Map all pixels to nearest palette index
    const indexedGrid = new Uint8Array(pixelCount);
    const indexCounts = new Uint32Array(paletteRgb.length);

    for (let p = 0; p < pixelCount; p++) {
      const idx = p * 4;
      const a = data[idx + 3];
      if (a < 30) {
        indexedGrid[p] = 255; // transparent indicator
        continue;
      }
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];

      let nearestIdx = 0;
      let minDist = Infinity;
      for (let k = 0; k < paletteRgb.length; k++) {
        const pr = paletteRgb[k][0];
        const pg = paletteRgb[k][1];
        const pb = paletteRgb[k][2];
        const dist = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2;
        if (dist < minDist) {
          minDist = dist;
          nearestIdx = k;
        }
      }

      indexedGrid[p] = nearestIdx;
      indexCounts[nearestIdx]++;
    }

    // Identify dominant background index
    let bgIdx = 0;
    let maxCount = 0;
    for (let k = 0; k < indexCounts.length; k++) {
      if (indexCounts[k] > maxCount) {
        maxCount = indexCounts[k];
        bgIdx = k;
      }
    }

    // Step 4: Extract contours per color index
    const paths = [];

    for (let k = 0; k < paletteRgb.length; k++) {
      if (transparentBg && k === bgIdx) continue;

      const hexColor = paletteHex[k];
      const contours = this.extractContoursForIndex(indexedGrid, k, w, h, minArea);

      for (const contour of contours) {
        const simplified = this.ramerDouglasPeucker(contour, epsilon);
        if (simplified.length < 3) continue;

        let dStr = '';
        if (curveType === 'bezier') {
          dStr = this.pointsToBezierPath(simplified);
        } else {
          dStr = this.pointsToPolygonPath(simplified);
        }

        const isBg = (k === bgIdx);
        paths.push({
          d: dStr,
          fill: hexColor,
          stroke: hexColor,
          strokeWidth: 0.4,
          pointCount: simplified.length,
          area: contour.area,
          isBg
        });
      }
    }

    // Sort paths: Background shapes first, then largest to smallest
    paths.sort((a, b) => {
      if (a.isBg !== b.isBg) return a.isBg ? -1 : 1;
      return b.area - a.area;
    });

    return { paths, palette: paletteHex };
  }

  /**
   * Monochrome / Line Art Processing Logic
   */
  processMonochrome(imageData, w, h, epsilon, minArea, curveType) {
    const data = imageData.data;
    const pixelCount = w * h;
    const binaryGrid = new Uint8Array(pixelCount);

    // Convert to Luminance Threshold
    for (let i = 0; i < pixelCount; i++) {
      const idx = i * 4;
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];
      const lum = 0.299 * r + 0.587 * g + 0.114 * b;
      binaryGrid[i] = lum < 128 ? 1 : 0; // Dark pixel = 1
    }

    const contours = this.extractContoursForIndex(binaryGrid, 1, w, h, minArea);
    const paths = [];

    for (const contour of contours) {
      const simplified = this.ramerDouglasPeucker(contour, epsilon);
      if (simplified.length < 3) continue;

      const dStr = curveType === 'bezier' ? this.pointsToBezierPath(simplified) : this.pointsToPolygonPath(simplified);
      paths.push({
        d: dStr,
        fill: '#111827',
        stroke: '#111827',
        strokeWidth: 0.5,
        pointCount: simplified.length,
        area: contour.area,
        isBg: false
      });
    }

    return { paths, palette: ['#111827', '#ffffff'] };
  }

  /**
   * Contour Extraction via Grid Boundary Marching
   */
  extractContoursForIndex(grid, targetIdx, w, h, minArea) {
    const visited = new Uint8Array(w * h);
    const contours = [];

    for (let y = 0; y < h; y += 2) {
      for (let x = 0; x < w; x += 2) {
        const idx = y * w + x;
        if (grid[idx] === targetIdx && !visited[idx]) {
          const points = this.traceBoundary(grid, targetIdx, x, y, w, h, visited);
          if (points && points.length >= 4) {
            const area = this.calculatePolygonArea(points);
            if (area >= minArea) {
              points.area = area;
              contours.push(points);
            }
          }
        }
      }
    }

    return contours;
  }

  /**
   * Boundary Tracer for Single Region
   */
  traceBoundary(grid, targetIdx, startX, startY, w, h, visited) {
    const points = [];
    let cx = startX;
    let cy = startY;

    // Directions: R, D, L, U
    const dx = [1, 0, -1, 0];
    const dy = [0, 1, 0, -1];
    let dir = 0;

    const maxSteps = w * h;
    let steps = 0;

    while (steps < maxSteps) {
      points.push({ x: cx, y: cy });
      const idx = cy * w + cx;
      visited[idx] = 1;

      let found = false;
      for (let i = 0; i < 4; i++) {
        const testDir = (dir + 3 + i) % 4; // Check left-hand rule turn first
        const nx = cx + dx[testDir];
        const ny = cy + dy[testDir];

        if (nx >= 0 && nx < w && ny >= 0 && ny < h) {
          if (grid[ny * w + nx] === targetIdx) {
            cx = nx;
            cy = ny;
            dir = testDir;
            found = true;
            break;
          }
        }
      }

      if (!found || (cx === startX && cy === startY && points.length > 2)) {
        break;
      }
      steps++;
    }

    return points;
  }

  /**
   * Ramer-Douglas-Peucker (RDP) Curve Simplification Algorithm
   */
  ramerDouglasPeucker(points, epsilon) {
    if (points.length <= 2) return points;

    let maxDist = 0;
    let index = 0;
    const end = points.length - 1;

    for (let i = 1; i < end; i++) {
      const dist = this.perpendicularDistance(points[i], points[0], points[end]);
      if (dist > maxDist) {
        maxDist = dist;
        index = i;
      }
    }

    if (maxDist > epsilon) {
      const recResults1 = this.ramerDouglasPeucker(points.slice(0, index + 1), epsilon);
      const recResults2 = this.ramerDouglasPeucker(points.slice(index), epsilon);
      return recResults1.slice(0, recResults1.length - 1).concat(recResults2);
    } else {
      return [points[0], points[end]];
    }
  }

  perpendicularDistance(pt, lineStart, lineEnd) {
    const dx = lineEnd.x - lineStart.x;
    const dy = lineEnd.y - lineStart.y;
    const mag = Math.hypot(dx, dy);
    if (mag === 0) return Math.hypot(pt.x - lineStart.x, pt.y - lineStart.y);

    const u = ((pt.x - lineStart.x) * dx + (pt.y - lineStart.y) * dy) / (mag * mag);
    const ix = lineStart.x + u * dx;
    const iy = lineStart.y + u * dy;
    return Math.hypot(pt.x - ix, pt.y - iy);
  }

  /**
   * Convert Points Array to Polygon SVG Path Data (M ... L ... Z)
   */
  pointsToPolygonPath(pts) {
    if (!pts || pts.length === 0) return '';
    const parts = [`M ${pts[0].x},${pts[0].y}`];
    for (let i = 1; i < pts.length; i++) {
      parts.push(`L ${pts[i].x},${pts[i].y}`);
    }
    parts.push('Z');
    return parts.join(' ');
  }

  /**
   * Convert Points Array to Smooth Bezier SVG Path Data
   */
  pointsToBezierPath(pts) {
    if (!pts || pts.length === 0) return '';
    if (pts.length < 3) return this.pointsToPolygonPath(pts);

    const parts = [`M ${pts[0].x},${pts[0].y}`];
    const len = pts.length;

    for (let i = 0; i < len; i++) {
      const p0 = pts[(i - 1 + len) % len];
      const p1 = pts[i];
      const p2 = pts[(i + 1) % len];
      const p3 = pts[(i + 2) % len];

      // Smooth Catmull-Rom to Cubic Bezier control points calculation
      const cp1x = Math.round(p1.x + (p2.x - p0.x) / 6);
      const cp1y = Math.round(p1.y + (p2.y - p0.y) / 6);
      const cp2x = Math.round(p2.x - (p3.x - p1.x) / 6);
      const cp2y = Math.round(p2.y - (p3.y - p1.y) / 6);

      parts.push(`C ${cp1x},${cp1y} ${cp2x},${cp2y} ${p2.x},${p2.y}`);
    }

    parts.push('Z');
    return parts.join(' ');
  }

  /**
   * K-Means Palette Clustering
   */
  kMeansQuantize(samples, k, maxIterations = 8) {
    if (samples.length === 0) return [[0, 0, 0]];
    k = Math.min(k, samples.length);

    // Initial centroids picked randomly
    let centroids = [];
    const step = Math.floor(samples.length / k);
    for (let i = 0; i < k; i++) {
      centroids.push([...samples[i * step]]);
    }

    for (let iter = 0; iter < maxIterations; iter++) {
      const clusters = Array.from({ length: k }, () => []);

      // Assign samples to nearest centroid
      for (const s of samples) {
        let minDist = Infinity;
        let bestK = 0;
        for (let i = 0; i < k; i++) {
          const dist = (s[0] - centroids[i][0]) ** 2 + (s[1] - centroids[i][1]) ** 2 + (s[2] - centroids[i][2]) ** 2;
          if (dist < minDist) {
            minDist = dist;
            bestK = i;
          }
        }
        clusters[bestK].push(s);
      }

      // Update centroids
      let shift = 0;
      for (let i = 0; i < k; i++) {
        if (clusters[i].length === 0) continue;
        let sumR = 0, sumG = 0, sumB = 0;
        for (const pt of clusters[i]) {
          sumR += pt[0];
          sumG += pt[1];
          sumB += pt[2];
        }
        const newR = Math.round(sumR / clusters[i].length);
        const newG = Math.round(sumG / clusters[i].length);
        const newB = Math.round(sumB / clusters[i].length);

        shift += Math.abs(centroids[i][0] - newR) + Math.abs(centroids[i][1] - newG) + Math.abs(centroids[i][2] - newB);
        centroids[i] = [newR, newG, newB];
      }

      if (shift < 2) break; // converged
    }

    return centroids;
  }

  calculatePolygonArea(pts) {
    let area = 0;
    const j = pts.length - 1;
    for (let i = 0; i < pts.length; i++) {
      area += (pts[j].x + pts[i].x) * (pts[j].y - pts[i].y);
    }
    return Math.abs(area / 2);
  }

  rgbToHex(r, g, b) {
    return "#" + ((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1);
  }
}

// Export singleton instance
window.vectorizer = new VectorizerEngine();
